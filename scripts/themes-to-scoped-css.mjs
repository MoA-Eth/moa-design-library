#!/usr/bin/env node
/**
 * Generates docs-only theme artifacts and public runtime stylesheets from src/themes/*.css:
 *   - public/themes/<id>.css          runtime CSS files loaded by the header switcher & preview iframes
 *   - docs-nextra/themes-scoped.css   [data-moa-card-theme='<id>'] scoped variables for ThemeGallery
 *   - docs-nextra/themes-data.json    metadata & swatch values for ThemeGallery + ThemePlayground + dropdown
 */

import { mkdirSync, readdirSync, readFileSync, copyFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const THEMES_DIR = resolve(REPO_ROOT, 'src/themes');
const PUBLIC_THEMES_DIR = resolve(REPO_ROOT, 'public/themes');

const THEME_META = {
  default: {
    displayName: 'MoA Default',
    note: 'MoA green & national gold',
  },
  'highland-slate': {
    displayName: 'Highland Slate',
    note: 'Forest teal & crisp slate',
  },
  'harvest-earth': {
    displayName: 'Harvest Earth',
    note: 'Warm olive & harvest ochre',
  },
};

const PREVIEW_TOKENS = [
  'background',
  'foreground',
  'surface',
  'primary',
  'primary-hover',
  'primary-foreground',
  'secondary',
  'secondary-foreground',
  'muted',
  'muted-foreground',
  'accent',
  'accent-foreground',
  'destructive',
  'border',
  'input',
  'ring',
  'success-soft',
  'success-soft-foreground',
  'success-soft-border',
  'info-soft',
  'info-soft-foreground',
  'info-soft-border',
  'warning-soft',
  'warning-soft-foreground',
  'warning-soft-border',
  'danger-soft',
  'danger-soft-foreground',
  'danger-soft-border',
  'neutral-soft',
  'neutral-soft-foreground',
  'neutral-soft-border',
  'radius',
];

function toTitleCase(id) {
  return id
    .split(/[-_]+/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(' ');
}

function parseThemeCss(cssText) {
  const cleaned = cssText.replace(/\/\*[\s\S]*?\*\//g, '');
  const blockRe = /([:.][\w-]+)\s*\{([^}]*)\}/g;
  const out = { light: {}, dark: {} };
  let match;

  while ((match = blockRe.exec(cleaned)) !== null) {
    const selector = match[1];
    const body = match[2];
    const bucket = selector === ':root' ? 'light' : selector === '.dark' ? 'dark' : null;
    if (!bucket) continue;

    const declRe = /(--[\w-]+)\s*:\s*([^;]+);/g;
    let decl;
    while ((decl = declRe.exec(body)) !== null) {
      out[bucket][decl[1]] = decl[2].trim();
    }
  }
  return out;
}

function pickPreviewTokens(tokenMap) {
  const out = {};
  for (const name of PREVIEW_TOKENS) {
    const key = `--${name}`;
    if (tokenMap[key] !== undefined) {
      out[name] = tokenMap[key];
    }
  }
  return out;
}

function emitDeclarations(tokenMap, indent = '  ') {
  return Object.entries(tokenMap)
    .map(([name, value]) => `${indent}${name}: ${value};`)
    .join('\n');
}

mkdirSync(PUBLIC_THEMES_DIR, { recursive: true });

const themeIds = readdirSync(THEMES_DIR)
  .filter((file) => file.endsWith('.css') && file !== 'active.css')
  .map((file) => file.replace(/\.css$/, ''))
  .sort((a, b) => {
    if (a === 'default') return -1;
    if (b === 'default') return 1;
    return a.localeCompare(b);
  });

const cssLines = ['/* Auto-generated by scripts/themes-to-scoped-css.mjs. Do not edit. */', '/* Source: src/themes/*.css */', ''];
const data = [];

for (const id of themeIds) {
  const srcPath = resolve(THEMES_DIR, `${id}.css`);
  const publicPath = resolve(PUBLIC_THEMES_DIR, `${id}.css`);
  copyFileSync(srcPath, publicPath);

  const cssText = readFileSync(srcPath, 'utf8');
  const tokens = parseThemeCss(cssText);
  const meta = THEME_META[id] ?? { displayName: toTitleCase(id), note: 'MoA custom theme' };

  cssLines.push(`[data-moa-card-theme='${id}'] {`);
  cssLines.push(emitDeclarations(tokens.light));
  cssLines.push('}');
  if (Object.keys(tokens.dark).length > 0) {
    cssLines.push(`[data-moa-card-theme='${id}'].dark {`);
    cssLines.push(emitDeclarations(tokens.dark));
    cssLines.push('}');
  }
  cssLines.push('');

  data.push({
    id,
    displayName: meta.displayName,
    note: meta.note,
    light: pickPreviewTokens(tokens.light),
    dark: pickPreviewTokens(tokens.dark),
  });
}

writeFileSync(resolve(REPO_ROOT, 'docs-nextra/themes-scoped.css'), cssLines.join('\n'));
writeFileSync(resolve(REPO_ROOT, 'docs-nextra/themes-data.json'), `${JSON.stringify(data, null, 2)}\n`);

console.log(`themes:codegen wrote ${themeIds.length} theme(s) -> public/themes/, docs-nextra/themes-scoped.css + themes-data.json`);
