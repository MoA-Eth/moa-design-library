#!/usr/bin/env node
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHighlighter } from 'shiki';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, '..');
const registryRoot = path.join(repoRoot, 'docs-nextra', 'registry');
const generatedDir = path.join(registryRoot, 'generated');
const exampleCodeFile = path.join(generatedDir, 'exampleCode.ts');
const flowFilesFile = path.join(generatedDir, 'flowFiles.ts');

const FLOW_FILE_PATTERN = /\.(tsx?|css|json)$/;
const SHIKI_LANGS = ['tsx', 'ts', 'jsx', 'js', 'css', 'json', 'md'];
const SHIKI_THEMES = { light: 'github-light', dark: 'github-dark' };

async function safeReaddir(dir) {
  try {
    return await fs.readdir(dir, { withFileTypes: true });
  } catch (error) {
    if (error.code === 'ENOENT') {
      return [];
    }
    throw error;
  }
}

function detectLanguage(filePath) {
  const ext = path.extname(filePath).slice(1);
  if (ext === 'tsx' || ext === 'ts' || ext === 'jsx' || ext === 'js' || ext === 'css' || ext === 'json' || ext === 'md') {
    return ext;
  }
  return 'tsx';
}

function highlight(highlighter, content, language) {
  try {
    return highlighter.codeToHtml(content, {
      lang: language,
      themes: SHIKI_THEMES,
    });
  } catch (error) {
    console.warn(`[gen:example-code] shiki failed (${language}):`, error?.message ?? error);
    return '';
  }
}

async function collectComponentExamples(highlighter) {
  const componentsRoot = path.join(registryRoot, 'components');
  const dirs = await safeReaddir(componentsRoot);
  const result = {};

  for (const dir of dirs) {
    if (!dir.isDirectory()) continue;
    const componentDir = path.join(componentsRoot, dir.name);
    const files = await safeReaddir(componentDir);
    const exampleFile = files.find((file) => file.isFile() && file.name.endsWith('.tsx'));
    if (!exampleFile) continue;

    const absPath = path.join(componentDir, exampleFile.name);
    const raw = await fs.readFile(absPath, 'utf8');
    // Rewrite internal docs alias if any so displayed code shows public package import
    const code = raw.trimEnd();
    const html = highlight(highlighter, code, 'tsx');
    result[dir.name] = { code, html };
  }

  return result;
}

async function walkFlowFiles(dir) {
  const entries = await safeReaddir(dir);
  const collected = [];
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      collected.push(...(await walkFlowFiles(full)));
    } else if (entry.isFile() && FLOW_FILE_PATTERN.test(entry.name)) {
      collected.push(full);
    }
  }
  return collected;
}

function compareFlowPaths(a, b) {
  const aDepth = a.split('/').length;
  const bDepth = b.split('/').length;
  if (aDepth !== bDepth) return aDepth - bDepth;
  return a.localeCompare(b);
}

async function collectFlowFiles(highlighter) {
  const flowsRoot = path.join(registryRoot, 'flows');
  const dirs = await safeReaddir(flowsRoot);
  const result = {};

  for (const dir of dirs) {
    if (!dir.isDirectory()) continue;
    const flowDir = path.join(flowsRoot, dir.name);
    const absPaths = await walkFlowFiles(flowDir);
    if (absPaths.length === 0) continue;

    const files = await Promise.all(
      absPaths.map(async (absPath) => {
        const relPath = path.relative(flowDir, absPath).split(path.sep).join('/');
        const content = await fs.readFile(absPath, 'utf8');
        const language = detectLanguage(absPath);
        const html = highlight(highlighter, content, language);
        return { path: relPath, content, language, html };
      }),
    );
    files.sort((a, b) => compareFlowPaths(a.path, b.path));
    result[dir.name] = files;
  }

  return result;
}

function serializeExampleCode(examples) {
  const lines = [
    '// AUTO-GENERATED by scripts/generate-example-code-manifest.mjs. Do not edit.',
    '',
    'export type ComponentExampleCodeEntry = Readonly<{',
    '  code: string;',
    '  html: string;',
    '}>;',
    '',
    'export const EXAMPLE_CODE: Record<string, ComponentExampleCodeEntry> = {',
  ];

  for (const id of Object.keys(examples).sort()) {
    const { code, html } = examples[id];
    lines.push(`  ${JSON.stringify(id)}: { code: ${JSON.stringify(code)}, html: ${JSON.stringify(html)} },`);
  }

  lines.push('};', '');
  return lines.join('\n');
}

function serializeFlowFiles(flows) {
  const lines = [
    '// AUTO-GENERATED by scripts/generate-example-code-manifest.mjs. Do not edit.',
    '',
    'export type FlowExampleFile = Readonly<{',
    '  path: string;',
    '  content: string;',
    "  language: 'tsx' | 'ts' | 'jsx' | 'js' | 'css' | 'json' | 'md';",
    '  html: string;',
    '}>;',
    '',
    'export const FLOW_EXAMPLE_FILES: Record<string, readonly FlowExampleFile[]> = {',
  ];

  for (const flowId of Object.keys(flows).sort()) {
    lines.push(`  ${JSON.stringify(flowId)}: [`);
    for (const file of flows[flowId]) {
      lines.push(
        `    { path: ${JSON.stringify(file.path)}, language: ${JSON.stringify(file.language)}, content: ${JSON.stringify(file.content)}, html: ${JSON.stringify(file.html)} },`,
      );
    }
    lines.push('  ],');
  }

  lines.push('};', '');
  return lines.join('\n');
}

async function main() {
  await fs.mkdir(generatedDir, { recursive: true });

  const highlighter = await createHighlighter({
    themes: Object.values(SHIKI_THEMES),
    langs: SHIKI_LANGS,
  });

  const componentExamples = await collectComponentExamples(highlighter);
  await fs.writeFile(exampleCodeFile, serializeExampleCode(componentExamples), 'utf8');
  console.log(
    `[gen:example-code] wrote ${Object.keys(componentExamples).length} component example(s) -> ${path.relative(repoRoot, exampleCodeFile)}`,
  );

  const flows = await collectFlowFiles(highlighter);
  const totalFlowFiles = Object.values(flows).reduce((sum, files) => sum + files.length, 0);
  await fs.writeFile(flowFilesFile, serializeFlowFiles(flows), 'utf8');
  console.log(
    `[gen:example-code] wrote ${Object.keys(flows).length} flow(s) (${totalFlowFiles} files) -> ${path.relative(repoRoot, flowFilesFile)}`,
  );

  highlighter.dispose?.();
}

main().catch((error) => {
  console.error('[gen:example-code] failed:', error);
  process.exit(1);
});
