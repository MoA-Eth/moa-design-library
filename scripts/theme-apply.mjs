#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';

const rootDir = process.cwd();
const themesDir = path.resolve(rootDir, 'src/themes');
const activeCssPath = path.resolve(themesDir, 'active.css');

const args = process.argv.slice(2);
const flagIndex = args.indexOf('--theme');
const themeId = flagIndex !== -1 ? args[flagIndex + 1] : null;

if (!themeId) {
  console.error('Missing required argument: --theme <theme-id>');
  process.exit(1);
}

const targetPath = path.resolve(themesDir, `${themeId}.css`);
if (!fs.existsSync(targetPath)) {
  console.error(`Unknown theme id: ${themeId}`);
  process.exit(1);
}

const activeCss = ['/* Auto-generated by pnpm theme:apply. */', `@import './${themeId}.css';`, ''].join('\n');

fs.writeFileSync(activeCssPath, activeCss, 'utf8');
console.log(`Applied theme '${themeId}' to src/themes/active.css.`);
